import { nowIso, uuidv7 } from '@mindscope/core';
import type { SqlDriver } from '../driver';

// ── growth notes: the user's own dated observations about a person ─────

export interface GrowthNote {
  id: string;
  profileId: string;
  /** YYYY-MM-DD */
  date: string;
  text: string;
  createdAt: string;
  updatedAt: string;
}

export const GROWTH_NOTE_MAX = 2000;

interface GrowthRow {
  id: string;
  profile_id: string;
  date: string;
  text: string;
  created_at: string;
  updated_at: string;
}
const toGrowth = (r: GrowthRow): GrowthNote => ({
  id: r.id,
  profileId: r.profile_id,
  date: r.date,
  text: r.text,
  createdAt: r.created_at,
  updatedAt: r.updated_at,
});

function checkNote(date: string, text: string) {
  if (!/^\d{4}-\d{2}-\d{2}$/.test(date) || Number.isNaN(Date.parse(date))) throw new Error('INVALID_DATE');
  const t = text.trim();
  if (!t) throw new Error('EMPTY_TEXT');
  if (t.length > GROWTH_NOTE_MAX) throw new Error('TEXT_TOO_LONG');
  return t;
}

export class GrowthNotesRepository {
  constructor(private readonly db: SqlDriver) {}

  async list(profileId: string, limit = 500): Promise<GrowthNote[]> {
    const rows = await this.db.query<GrowthRow>(
      'SELECT * FROM growth_notes WHERE profile_id = ? ORDER BY date DESC, created_at DESC LIMIT ?',
      [profileId, limit],
    );
    return rows.map(toGrowth);
  }

  async add(profileId: string, date: string, text: string): Promise<GrowthNote> {
    const t = checkNote(date, text);
    const now = nowIso();
    const id = uuidv7();
    await this.db.execute('INSERT INTO growth_notes (id, profile_id, date, text, created_at, updated_at) VALUES (?, ?, ?, ?, ?, ?)', [
      id,
      profileId,
      date,
      t,
      now,
      now,
    ]);
    return { id, profileId, date, text: t, createdAt: now, updatedAt: now };
  }

  async update(id: string, date: string, text: string): Promise<void> {
    const t = checkNote(date, text);
    await this.db.execute('UPDATE growth_notes SET date = ?, text = ?, updated_at = ? WHERE id = ?', [date, t, nowIso(), id]);
  }

  async remove(id: string): Promise<boolean> {
    return (await this.db.execute('DELETE FROM growth_notes WHERE id = ?', [id])).changes > 0;
  }
}

// ── AI notes: text generated by an AI provider, with what it was based on ──

export type AiTask = 'history' | 'growth' | 'advice';

export interface AiBasis {
  /** Short lines generated by the app, e.g. "3 personality results (2026-01-02 to 2026-10-20)". */
  lines: string[];
}

export interface AiNote {
  id: string;
  profileId: string;
  task: AiTask;
  model: string;
  promptVersion: string;
  categories: string[];
  basis: AiBasis;
  /** A PHQ-9 safety item was part of the data sent: always show crisis resources. */
  safety: boolean;
  content: string;
  createdAt: string;
}

interface AiRow {
  id: string;
  profile_id: string;
  task: string;
  model: string;
  prompt_version: string;
  categories_json: string;
  basis_json: string;
  safety: number;
  content: string;
  created_at: string;
}
const toAi = (r: AiRow): AiNote => ({
  id: r.id,
  profileId: r.profile_id,
  task: r.task as AiTask,
  model: r.model,
  promptVersion: r.prompt_version,
  categories: JSON.parse(r.categories_json) as string[],
  basis: JSON.parse(r.basis_json) as AiBasis,
  safety: r.safety === 1,
  content: r.content,
  createdAt: r.created_at,
});

export class AiNotesRepository {
  constructor(private readonly db: SqlDriver) {}

  async list(profileId: string): Promise<AiNote[]> {
    const rows = await this.db.query<AiRow>('SELECT * FROM ai_notes WHERE profile_id = ? ORDER BY created_at DESC, id DESC', [profileId]);
    return rows.map(toAi);
  }

  async get(id: string): Promise<AiNote | null> {
    const [row] = await this.db.query<AiRow>('SELECT * FROM ai_notes WHERE id = ?', [id]);
    return row ? toAi(row) : null;
  }

  async add(note: Omit<AiNote, 'id' | 'createdAt'>): Promise<AiNote> {
    const id = uuidv7();
    const createdAt = nowIso();
    await this.db.execute(
      `INSERT INTO ai_notes (id, profile_id, task, model, prompt_version, categories_json, basis_json, safety, content, created_at)
       VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?)`,
      [
        id,
        note.profileId,
        note.task,
        note.model,
        note.promptVersion,
        JSON.stringify(note.categories),
        JSON.stringify(note.basis),
        note.safety ? 1 : 0,
        note.content,
        createdAt,
      ],
    );
    return { ...note, id, createdAt };
  }

  async remove(id: string): Promise<boolean> {
    return (await this.db.execute('DELETE FROM ai_notes WHERE id = ?', [id])).changes > 0;
  }
}

// ── network record (written by the desktop shell for every request) ─────

export interface NetworkRecord {
  id: string;
  at: string;
  endpoint: string;
  purpose: string;
  categories: string[];
  bytes: number;
  outcome: string;
  model: string;
  tokens: number;
}

export interface NetworkUsage {
  requests: number;
  ok: number;
  tokens: number;
  lastAt: string | null;
  lastOutcome: string | null;
}

interface NetworkRow {
  id: string;
  at: string;
  endpoint: string;
  purpose: string;
  categories_json: string;
  bytes: number;
  outcome: string;
  model: string;
  tokens: number;
}

export class NetworkAuditRepository {
  constructor(private readonly db: SqlDriver) {}

  async list(limit = 200): Promise<NetworkRecord[]> {
    const rows = await this.db.query<NetworkRow>('SELECT * FROM network_audit ORDER BY at DESC, id DESC LIMIT ?', [limit]);
    return rows.map((r) => ({
      id: r.id,
      at: r.at,
      endpoint: r.endpoint,
      purpose: r.purpose,
      categories: JSON.parse(r.categories_json) as string[],
      bytes: r.bytes,
      outcome: r.outcome,
      model: r.model,
      tokens: r.tokens,
    }));
  }

  async usage(): Promise<NetworkUsage> {
    const [row] = await this.db.query<{ n: number; ok: number | null; tokens: number | null }>(
      "SELECT COUNT(*) AS n, SUM(CASE WHEN outcome = 'ok' THEN 1 ELSE 0 END) AS ok, SUM(tokens) AS tokens FROM network_audit",
    );
    const [last] = await this.db.query<{ at: string; outcome: string }>('SELECT at, outcome FROM network_audit ORDER BY at DESC, id DESC LIMIT 1');
    return { requests: row?.n ?? 0, ok: row?.ok ?? 0, tokens: row?.tokens ?? 0, lastAt: last?.at ?? null, lastOutcome: last?.outcome ?? null };
  }

  /** Used by the test build's simulated provider and by tests; the desktop shell writes its own rows. */
  async record(r: Omit<NetworkRecord, 'id' | 'at'>): Promise<void> {
    await this.db.execute(
      'INSERT INTO network_audit (id, at, endpoint, purpose, categories_json, bytes, outcome, model, tokens) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)',
      [uuidv7(), nowIso(), r.endpoint, r.purpose, JSON.stringify(r.categories), r.bytes, r.outcome, r.model, r.tokens],
    );
  }

  async clear(): Promise<void> {
    await this.db.execute('DELETE FROM network_audit');
  }
}
